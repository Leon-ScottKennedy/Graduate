const { demoParts } = loader('../src/data/mock/catalog.ts')
const { browseHardware } = loader('../src/services/hardwareBrowse.ts')
let total = 0
let completeEnough = 0
for (const group of demoParts) {
  const options = browseHardware(group)
  let recorded = 0
  for (const part of options) {
    const details = partSpecifications(part, group.id)
    assert.ok(details.length >= 3, `${group.id}: ${part.name} must expose category-specific fields`)
    const known = details.filter(row => row.value !== '待补充')
    assert.ok(known.length >= 1, `${part.name} has no recorded parameter`)
    if (known.length >= 3) { recorded++; completeEnough++ }
    assert.equal(new Set(details.map(row => row.label)).size, details.length)
    total++
  }
  console.log(`${group.label}: ${options.length} models, ${recorded} have at least 3 recorded parameter fields`)
}
console.log(`Inspected all ${total} catalog models across 8 hardware categories`)
assert.ok(completeEnough / total >= .95, 'At least 95% of all listed hardware must have 3 or more real parameter fields')
